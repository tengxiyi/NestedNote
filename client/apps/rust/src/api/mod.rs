//! 跨 FFI 暴露给 Flutter 的 API。
//!
//! ## 为什么要单独一层
//!
//! `flutter_rust_bridge` 的 `rust_input` 指向 `crate::api`，因此**只有本模块下的
//! 函数会被导出到 Dart**。这样分层带来两个好处：
//!
//! 1. **导出面可控**：不会被"顺手 pub 出来的内部函数"意外暴露（铁律 A3）；
//! 2. **契约集中**：所有跨语言边界的东西都在一处，便于审计参数与返回值。
//!
//! ## 铁律约束（A3 / A4 / E1）
//!
//! - 只暴露**业务语义**，不暴露 `execute_sql` 之类的实现细节；
//! - 跨边界只传可序列化的简单结构，不传裸指针、不传数据库句柄；
//! - 所有函数**禁止** panic：错误一律转成结构化结果返回。

