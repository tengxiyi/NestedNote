-- 拾光笔记 / NestedNote —— 本地 SQLite 迁移 0003
-- 为修订保存**内容快照**（"修订对比"的数据基础）
--
-- 背景：
--   0001 的 `revisions` 表只存元数据（version / 时间 / 设备 / 操作 / 父指针），
--   没有内容列。设计文档 §4.8 把它定位为"追加型审计"，
--   把"含内容的版本历史"划到 P7。
--
--   因此"修订对比"这个功能此前**没有数据可对比**。本迁移补上这一层。
--
-- 决策依据：docs/adr/0001-修订内容用完整快照.md
--   结论是**完整快照**而不是差量（delta）。理由摘要：
--     · 正确性优先：一条修订 = 一份完整内容，不存在"重放链条出错"的可能；
--     · 差量把"读取"变成有状态重放，任何一处链条断裂会让整条历史不可读，
--       而失败形式是"读到一半发现不对"，最难处理；
--     · 实测序列化文档平均约 375 字节（含最大 603 字节），
--       当前规模下完整快照的存储代价可以接受。
--   代价（明确接受）：重度使用时快照总量可能到数百 MB。
--   若将来成为真实问题，应基于实测数据另开 ADR，而不是现在预防性引入重放复杂度。
--
-- 铁律约束：
--   Q2：已发布的 0001/0002 不可修改，因此这里新建一条迁移。
--   D1：快照与 `revisions` 行必须在**同一事务**里写入。
--   T1：快照缺失时**不得**用当前内容回填——那是在伪造审计材料。
-- =============================================================================

CREATE TABLE revision_documents (
    revision_id BLOB PRIMARY KEY REFERENCES revisions (id),
    -- 与 documents.content 使用**同一序列化格式**（块模型 JSON 字节）。
    -- 共用格式的好处：对比时不必转换，且将来格式演进只需处理一处版本号。
    content     BLOB NOT NULL
);

-- 读取模式说明（不额外建索引的原因）：
--   唯一的查询是"给定 revision_id 取快照"，而 revision_id 是主键，
--   已有隐式索引。反向查询（"某笔记的所有快照"）走 revisions 表的
--   idx_revisions_note，因此这里不需要第二个索引。
--
-- 历史数据的处理：
--   本迁移**之前**产生的 revisions 行没有对应快照，故意不补。
--   代码侧用 LEFT JOIN 读取，缺失时返回 None，界面显示
--   "此版本没有内容快照（早于快照功能）"，而不是显示空白 diff——
--   空白会让用户以为"这一版是空的"，从而怀疑数据损坏。
