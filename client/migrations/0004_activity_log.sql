-- =============================================================================
-- 拾光笔记 / NestedNote —— 本地 SQLite 迁移 0004
-- 活动日志（"工具 → 活动日志"的数据基础）
--
-- 背景：
--   自动清理是全项目唯一"用户没操作、数据却消失"的路径
--   （回收站到期清理、附件 GC）。铁律 T1 的修订说明承诺了三重防御，
--   其中"可追溯"此前只有日志框架（tracing，开发者才能看），
--   用户在界面上没有任何地方能看到"应用对我的数据做了什么"。
--
--   本迁移补上这一层：破坏性/维护性操作落库留痕。
--
-- 范围刻意收窄：
--   只记**维护/破坏性**事件（回收站清理、附件 GC、完整性核对）。
--   笔记级变更修订历史已经完整记录（revisions），重复记一遍是噪音。
--
-- 事件行**只追加、不更新、不删除**：审计记录被改动比缺失更糟。
-- 历史条目不设上限——按现有写入频率（手动触发维护），
-- 一年也产生不了几百条，不值得为它做轮转。
-- =============================================================================

CREATE TABLE activity_events (
    -- UUIDv7（16 字节），与全库其它主键同一代法
    event_id BLOB PRIMARY KEY,
    -- 事件发生时间（UTC 毫秒，与全库时间约定一致）
    at_ms   INTEGER NOT NULL,
    -- 事件类型，如 'trash.purge' / 'attachments.gc' / 'integrity.check'
    kind    TEXT NOT NULL,
    -- 给人看的说明（含关键数字），界面直接展示
    detail  TEXT NOT NULL
);

-- 列表按时间倒序取最近若干条
CREATE INDEX idx_activity_events_at ON activity_events (at_ms DESC);
